#!/bin/sh
# embed.sh OUT.h NAME=FILE [NAME=FILE...]
# Emits C string constants (one per file) for build-time HTML embedding.
# Lines are joined with "\n"; the caller includes the generated header.
set -eu
out=$1; shift
printf '/* generated by scripts/embed.sh - do not edit */\n' > "$out"
for pair in "$@"; do
    name=${pair%%=*}
    file=${pair#*=}
    printf 'static const char %s[] =\n' "$name" >> "$out"
    awk '{ gsub(/\\/,"\\\\"); gsub(/"/,"\\\""); printf "\"%s\\n\"\n", $0 }' "$file" >> "$out"
    printf ';\n' >> "$out"
done
